#!/usr/bin/env python3
"""Generate TypeScript declarations from what the API actually returns.

`docs/limitations.md` has carried "hand-mirrored frontend types" since the beginning, and the
reason given for not generating them was that every endpoint returns `dict[str, object]`, so
OpenAPI carries no response schema and a generator would emit `unknown`. That reasoning is
correct **and it is about one route to the answer.** The other route does not need a schema at
all: call the endpoint, look at what comes back, and write down its shape.

That is what this does. It builds a seeded instance, calls a curated list of read endpoints, and
infers an interface per response object. The result describes the thing the screens actually
receive -- not the thing an annotation claims they receive.

## What that buys, and what it does not

Four times a table drew nothing for every row because a screen declared `ruleType` and the
endpoint sent `rule_type`. Nothing failed: the types checked out, the linter saw a valid string,
the request succeeded. A generated file turns that class of change into a **diff** -- the
generator's output stops matching, `tests/test_generated_types.py` fails, and the reviewer sees
which field moved.

It does not remove the hand-written `frontend/src/types/index.ts`. That file also carries view
models and request payloads, and the generator only knows about responses. What it removes is the
part where a wrong answer is invisible.

## Determinism

Every list in the output is sorted, object keys are emitted in a stable order (sorted), and the
seeded instance is built the same way every run -- so regenerating an unchanged platform
produces a byte-identical file, which is what makes "the committed file is current" a testable
claim rather than a habit.
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

# Read endpoints, chosen because a screen charts them. `(name, path)`; the name becomes the
# interface name, so it is the page's word for the thing rather than the endpoint's.
ENDPOINTS: tuple[tuple[str, str], ...] = (
    ("OntologySummary", "/ontologies"),
    ("DataSourceSummary", "/data-sources"),
    ("SemanticMapping", "/ontologies/1/mappings"),
    ("BusinessRule", "/ontologies/1/rules"),
    ("SourceTableRow", "/data-sources/1/tables"),
    ("SourceApi", "/data-sources/1/apis"),
    ("PermissionPolicy", "/permissions/policies"),
    ("PermissionRole", "/permissions/roles"),
    ("ToolDefinition", "/tools"),
    ("AuditLogEntry", "/governance/audit-log"),
    ("ModelInvocationEntry", "/governance/model-invocations"),
    ("DecisionRecordEntry", "/governance/decisions"),
    ("WorkbenchActionItem", "/workbench"),
)

# Keys whose value is a list of objects get their own interface. The name is derived from the
# key, so a new one appears without anybody editing a table -- which is the point.
_HEADER = """/**
 * Generated by `scripts/generate_types.py`. Do not edit by hand.
 *
 * Every field here was observed on a response from a seeded instance, not read off an
 * annotation -- the platform's endpoints return `dict[str, object]`, so there is no schema to
 * generate from and this is the other route to the same answer.
 *
 * Regenerate with `python scripts/generate_types.py`. `tests/test_generated_types.py` fails
 * when this file stops matching what the API sends, which turns "a field was renamed" into a
 * diff on a generated file instead of a column that quietly renders empty.
 *
 * Optional (`?`) means the field was absent from at least one object of its kind. `unknown`
 * means it held more than one type across the sample, which is worth looking at rather than
 * papering over.
 */

"""


def _snake_to_pascal(name: str) -> str:
    parts = re.split(r"[_\-\s]+", name)
    return "".join(part[:1].upper() + part[1:] for part in parts if part)


def _infer(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int):
        return "number"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        if not value:
            # No evidence either way. `unknown[]` says that; `null[]` would claim the elements
            # are null, which is a statement this has no basis for.
            return "unknown[]"
        return f"{_merge([_infer(item) for item in value])}[]"
    if isinstance(value, dict):
        return "Record<string, unknown>"
    return "unknown"


def _merge(types: list[str]) -> str:
    """One type from several observations: `unknown` when they disagree."""
    unique = sorted(set(types))
    # `null` alongside a real type is a nullable field rather than a union worth naming.
    without_null = [item for item in unique if item != "null"]
    if len(without_null) == 1:
        return without_null[0]
    if not without_null:
        return "null"
    return "unknown"


def _collect_objects(rows: list[Any], name: str, out: dict[str, dict[str, str]]) -> str:
    """Fold a list of objects into `out[name]`, returning the TypeScript type for the list."""
    objects = [row for row in rows if isinstance(row, dict)]
    if not objects:
        return "unknown[]"
    fields: dict[str, list[str]] = {}
    presence: dict[str, int] = {}
    for row in objects:
        for key, value in row.items():
            fields.setdefault(key, []).append(_infer(value))
            presence[key] = presence.get(key, 0) + 1
    declaration: dict[str, str] = {}
    for key, seen in fields.items():
        optional = "?" if presence[key] < len(objects) else ""
        declaration[key + optional] = _merge(seen)
    # Merge rather than replace: the same key can appear under two endpoints, and the union of
    # what was observed is the truthful answer.
    if name in out:
        out[name].update(declaration)
    else:
        out[name] = declaration
    return f"{name}[]"


def infer_types(payloads: dict[str, Any]) -> dict[str, dict[str, str]]:
    """Interfaces from `{name: response}`, one level into each list and object it contains.

    **Nested interfaces are named after their parent, not after their key.** The first version
    used the key alone, and every one of these endpoints carries an `items` list -- so all
    twenty-one interfaces collapsed into one called `Items`, holding the union of every field the
    API has. That is worse than not generating at all: it would tell a reader that an audit entry
    has a `confidence`, and it would typecheck.
    """
    interfaces: dict[str, dict[str, str]] = {}
    for name, payload in payloads.items():
        if isinstance(payload, list):
            _collect_objects(payload, name, interfaces)
            continue
        if not isinstance(payload, dict):
            continue
        top: dict[str, str] = {}
        for key, value in payload.items():
            nested = f"{name}{_snake_to_pascal(key)}"
            if isinstance(value, list) and any(isinstance(item, dict) for item in value):
                top[key] = _collect_objects(value, nested, interfaces)
            elif isinstance(value, dict) and value:
                _collect_objects([value], nested, interfaces)
                top[key] = nested
            else:
                top[key] = _infer(value)
        interfaces[name] = top
    return interfaces


def render(interfaces: dict[str, dict[str, str]]) -> str:
    blocks = [_HEADER]
    for name in sorted(interfaces):
        blocks.append(f"export interface {name} {{")
        for field in sorted(interfaces[name]):
            # Field names come from the wire. A name that is not a bare identifier is quoted
            # rather than dropped: `dict(row)` can carry anything, and a silently missing field
            # is the defect this file exists to surface.
            safe = field if re.fullmatch(r"[A-Za-z_$][\w$]*\??", field) else f"'{field}'"
            blocks.append(f"  {safe}: {interfaces[name][field]};")
        blocks.append("}")
        blocks.append("")
    return "\n".join(blocks).rstrip() + "\n"


def collect_payloads() -> dict[str, Any]:
    """A seeded instance, queried through the real app.

    The seed is `aletheia demo` plus the smoke seeding, the same pair the render sweep uses, so
    the payloads here are the ones a deployment produces rather than fixtures written to match
    the generator.
    """
    import importlib

    with tempfile.TemporaryDirectory() as folder:
        base = Path(folder)
        platform_db = base / "platform.sqlite3"
        sample_db = base / "sample.sqlite3"

        import ontology_platform.database as database_module
        from ontology_platform.database import initialize_platform_db
        from ontology_platform.demo import run_contract_demo
        from ontology_platform.onboarding import run_onboarding_pipeline
        from ontology_platform.sample_data import create_contract_sample_db

        # Saved and restored: this rebinds a module global, and `generate()` is imported and
        # called in process by `tests/test_generated_types.py`. Leaving it pointed at a
        # temporary directory that is about to be deleted failed an unrelated packaging test --
        # the kind of leak that shows up as a flake in somebody else's file.
        previous_adapter = database_module._platform_adapter
        previous_default = getattr(database_module, "DEFAULT_PLATFORM_DB", None)
        database_module._platform_adapter = None
        database_module.DEFAULT_PLATFORM_DB = platform_db
        initialize_platform_db(platform_db)
        create_contract_sample_db(sample_db)
        # The same pair the render sweep and the contracts file use: `aletheia demo` for the
        # closed loop, then the smoke seeding for the screens the loop does not reach. A
        # generator fed hand-written fixtures would describe a payload no deployment produces.
        run_onboarding_pipeline(
            platform_db,
            "类型生成样例",
            "sqlite",
            str(sample_db),
            domain="合同管理",
            system_category="database+api",
            blueprint_id="contract-management",
        )
        del run_contract_demo
        _seed_smoke(platform_db)

        import ontology_platform.api as api_module
        from ontology_platform.auth import ensure_bootstrap_admin

        ensure_bootstrap_admin(platform_db)

        previous_api_default = api_module.DEFAULT_PLATFORM_DB
        api_module = importlib.reload(api_module)
        api_module.DEFAULT_PLATFORM_DB = platform_db

        from fastapi.testclient import TestClient

        try:
            with TestClient(api_module.app) as client:
                token = _sign_in(client, platform_db)
                headers = {"Authorization": f"Bearer {token}"}
                payloads: dict[str, Any] = {}
                for name, path in ENDPOINTS:
                    response = client.get(path, headers=headers)
                    if response.status_code != 200:
                        continue
                    payloads[name] = response.json()
                return payloads
        finally:
            database_module._platform_adapter = previous_adapter
            if previous_default is not None:
                database_module.DEFAULT_PLATFORM_DB = previous_default
            api_module.DEFAULT_PLATFORM_DB = previous_api_default
            importlib.reload(api_module)


def _seed_smoke(platform_db: Path) -> None:
    """Run `scripts/seed_smoke_instance.py`, which fills the eight screens the demo does not."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("seed_smoke_instance", ROOT / "scripts" / "seed_smoke_instance.py")
    if spec is None or spec.loader is None:  # pragma: no cover - import machinery
        return
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    # Every feature schema first: the seeding writes knowledge entries, tool reviews and tenant
    # rows, and those live in optional bundles that `initialize_platform_db` does not create.
    # `aletheia demo` does this for itself; calling the domain functions directly means doing it
    # here.
    from ontology_platform.bootstrap import prepare_database
    from ontology_platform.database import connect

    with connect(platform_db) as conn:
        prepare_database(conn)
    module.seed(platform_db)


def _sign_in(client: Any, platform_db: Path) -> str:
    """A token for the bootstrap administrator, whose password this script sets."""
    import os

    password = os.environ.get("ALETHEIA_TYPE_GEN_PASSWORD", "Type-Generation-Passw0rd")
    os.environ["ONTOLOGY_ADMIN_PASSWORD"] = password
    from ontology_platform.auth import reset_password

    reset_password(platform_db, "admin", password, actor="generate_types")
    response = client.post("/auth/login", json={"username": "admin", "password": password})
    return response.json()["token"]


def generate() -> str:
    return render(infer_types(collect_payloads()))


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate frontend response types from the API")
    parser.add_argument(
        "--output",
        default=str(ROOT / "frontend" / "src" / "types" / "generated.ts"),
        help="Where to write; defaults to frontend/src/types/generated.ts",
    )
    parser.add_argument("--check", action="store_true", help="Exit non-zero if the file is stale")
    args = parser.parse_args()

    rendered = generate()
    target = Path(args.output)
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            print(f"{target} 与当前 API 不符，请运行 python scripts/generate_types.py", file=sys.stderr)
            return 1
        print(f"{target} 是最新的")
        return 0
    target.write_text(rendered, encoding="utf-8")
    print(f"已写入 {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
