#!/usr/bin/env python3
"""Generate the key lists the normalisers produce, so `tsc` can hold the types to them.

The maturity page's gap says "not every response type can be generated, and the split is by
hand". Generating the *types* is not the answer: a normaliser writes `id: item.id`, from which
nothing better than `unknown` can be inferred, while the declared type says `number`. A generator
that produced the type would either lose that precision or read the hand-written declaration back
in and emit a copy of it -- a copy that hides changes rather than revealing them.

What *can* be generated is the part that is actually mechanical: **which keys each normaliser
writes**. Emitted as a `const` map, that list is then compared to the interface by TypeScript
itself, at build time, through the `Equal`/`Expect` pair in `types/index.ts`. So the key sets are
generated, the types stay hand-written and precise, and a drift between them fails `tsc` rather
than waiting for somebody to read a table.

`normalise.ts` is the source of truth: it is the code that runs. This script only reads it.

    python scripts/generate_normalised_keys.py            # update the file
    python scripts/generate_normalised_keys.py --check    # report staleness, change nothing
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NORMALISE = ROOT / "frontend" / "src" / "api" / "normalise.ts"
OUTPUT = ROOT / "frontend" / "src" / "types" / "normalised.ts"

SIGNATURE = re.compile(r"export const (?P<name>normalize\w+) = \(item: any\): (?P<type>\w+) => \(\{")
FIELD = re.compile(r"^\s{2}(?P<key>\w+):", re.MULTILINE)

HEADER = """// Generated by scripts/generate_normalised_keys.py -- do not edit.
//
// The keys each normaliser in `api/normalise.ts` writes, one list per declared type. The
// interfaces in `types/index.ts` are held to these lists by a compile-time assertion, so a
// key added to a normaliser without its type (or the reverse) fails `tsc` instead of blanking
// a column.
//
// `generated.ts` describes the *wire*; these describe what the client produces from it. Both
// are generated, from different sources, because neither can be derived from the other.

"""


def normalisers() -> list[tuple[str, str, list[str], bool]]:
    """`(function, type, keys, spreads the wire row)` for every normaliser in the file."""
    text = NORMALISE.read_text(encoding="utf-8")
    found: list[tuple[str, str, list[str], bool]] = []
    for match in SIGNATURE.finditer(text):
        start = match.end()
        depth, index = 1, start
        while index < len(text) and depth > 0:
            if text[index] == "{":
                depth += 1
            elif text[index] == "}":
                depth -= 1
            index += 1
        body = text[start : index - 1]
        found.append((match.group("name"), match.group("type"), FIELD.findall(body), "...item" in body))
    return found


def render() -> str:
    closed: list[tuple[str, list[str]]] = []
    spreading: list[tuple[str, list[str]]] = []
    for _function, type_name, keys, spread in normalisers():
        (spreading if spread else closed).append((type_name, keys))

    lines = [HEADER.rstrip(), ""]
    lines.append("/** Every key the normaliser writes, for the types that list all of them. */")
    lines.append("export const NORMALISED_FIELDS = {")
    for type_name, keys in sorted(closed):
        rendered = ", ".join(f"'{key}'" for key in keys)
        lines.append(f"  {type_name}: [{rendered}] as const,")
    lines.append("} as const;")
    lines.append("")
    lines.append("/**")
    lines.append(" * The keys a spreading normaliser *writes*, over and above the wire row it spreads.")
    lines.append(" *")
    lines.append(" * The type is open -- `...item` carries whatever the endpoint sent -- so these are held")
    lines.append(" * to a subset relation rather than an equality: every key written must exist on the type.")
    lines.append(" */")
    lines.append("export const NORMALISED_OVERRIDES = {")
    for type_name, keys in sorted(spreading):
        rendered = ", ".join(f"'{key}'" for key in keys)
        lines.append(f"  {type_name}: [{rendered}] as const,")
    lines.append("} as const;")
    lines.append("")
    return "\n".join(lines)


def generate() -> str:
    return render()


def main() -> int:
    parser = argparse.ArgumentParser(description="生成归一化函数写出的键列表")
    parser.add_argument("--check", action="store_true", help="只报告文件是否过期，不做修改")
    args = parser.parse_args()

    wanted = generate()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if wanted == current:
        print(f"{OUTPUT.relative_to(ROOT)} 是最新的。")
        return 0
    if args.check:
        print(
            f"{OUTPUT.relative_to(ROOT)} 与 normalise.ts 不符。运行 "
            "python scripts/generate_normalised_keys.py 重新生成，并让 tsc 检查类型是否仍与键一致。",
            file=sys.stderr,
        )
        return 1
    OUTPUT.write_text(wanted, encoding="utf-8")
    print(f"已更新 {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
