"""Request identity: one id that ties a response to its log lines.

Every request gets an id. It goes into the response header, into the structured log
record, and into the context that any code called during the request can read. That is
what makes "the user reported a 500 at 14:03" answerable -- without it, the only handle
on a request is its path, and a path is shared by every caller.

Three decisions worth stating, because each one has a plausible alternative that fails
quietly:

**An inbound id is validated, not trusted.** `X-Request-Id` from a caller is accepted so a
gateway or upstream service can correlate its own id with ours. But the value is written
into log lines, so a value carrying newlines or ANSI escapes lets a caller forge log
entries -- and a forged entry is worse than a missing one, because it is indistinguishable
from a real one. Only a conservative charset and length pass. A rejected value is
*replaced* rather than stripped down to its safe prefix: stripping would silently rewrite
the caller's id, so their correlation breaks for a reason nothing reports. A fresh id makes
the break visible in the mismatch.

**Ids are full UUID4 hex, not the first eight characters.** Eight hex characters is 32
bits. At a few thousand requests a day, the birthday bound puts a collision within weeks,
and a collision merges two unrelated requests into one log trail -- which reads exactly
like a request that logged twice.

**The context is set with a token and restored with it.** Clearing instead of restoring
loses the outer id: any nested scope (a background job started inside a request, a
sub-call that binds its own id) would blank the id for every log line emitted after it
returns. `reset()` puts back whatever was there before.
"""

from __future__ import annotations

import re
import uuid
from contextlib import contextmanager
from contextvars import ContextVar, Token
from typing import Iterator

# The header a caller may supply and the header we always answer with.
REQUEST_ID_HEADER = "X-Request-Id"

# Conservative on purpose: these are the characters that appear in ids generated by
# gateways, tracing systems and `uuidgen`. Anything else -- notably whitespace, newlines
# and escape sequences -- is refused rather than escaped.
_ALLOWED_INBOUND_ID = re.compile(r"\A[A-Za-z0-9._:-]+\Z")

# Long enough for a W3C traceparent, short enough that an id cannot be used to push the
# real log payload out of view.
MAX_REQUEST_ID_LENGTH = 128

_request_id: ContextVar[str] = ContextVar("request_id", default="")


def new_request_id() -> str:
    """A fresh id. Full UUID4 hex -- see the module docstring for why not a prefix."""
    return uuid.uuid4().hex


def sanitize_request_id(value: str | None) -> str:
    """An inbound id if it is safe to log, otherwise an empty string.

    Returns empty rather than raising: a malformed correlation header is not a reason to
    reject an otherwise valid request. The caller decides what an unusable id means, and
    the one caller here replaces it with a fresh one.
    """
    if not value:
        return ""
    candidate = value.strip()
    if not candidate or len(candidate) > MAX_REQUEST_ID_LENGTH:
        return ""
    if not _ALLOWED_INBOUND_ID.match(candidate):
        return ""
    return candidate


def current_request_id() -> str:
    """The id bound in this context, or an empty string outside a request."""
    return _request_id.get()


def bind_request_id(value: str | None = None) -> tuple[str, Token[str]]:
    """Bind an id to the current context and return it with the token that restores.

    An unusable `value` becomes a fresh id rather than an error, so callers that pass a
    caller-supplied header need no validation branch of their own.
    """
    request_id = sanitize_request_id(value) or new_request_id()
    return request_id, _request_id.set(request_id)


def reset_request_id(token: Token[str]) -> None:
    """Restore the id that was bound when `token` was issued."""
    _request_id.reset(token)


@contextmanager
def request_id_context(value: str | None = None) -> Iterator[str]:
    """Bind an id for the duration of the block, restoring the previous one after.

    The context-manager form exists so the restore cannot be forgotten: a `bind` without
    a matching `reset` leaves the id of a finished request attached to whatever runs next
    on the same context, which shows up as unrelated log lines claiming the same request.
    """
    request_id, token = bind_request_id(value)
    try:
        yield request_id
    finally:
        reset_request_id(token)
